"""Build, pin, and verify the corpus of this repository's own merged PRs.

One task is one merged `feat`/`fix` pull request:

* task text  — the linked issue's body, or the PR body's *Why This Exists*
  section when the PR closes no issue, stripped of anything that names the
  solution;
* workspace  — a detached worktree at the PR's merge base;
* validator  — the PR's own test files, materialized on top of whatever the
  candidate left behind, then run as unittest modules; a pass also requires
  the pre-existing regression modules for the touched packages to stay green.

Everything the run needs is pinned by digest here, so two runs weeks apart
compare like with like, and a run needs no network.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping, Sequence
from pathlib import Path
import re
import shutil
from tempfile import TemporaryDirectory
from typing import Any

import lane
import repo as repo_lib
from github import issue_body, merged_pull_requests

#: A conventional-commit `feat` or `fix` title, scope optional.
TITLE_PREFIX = re.compile(r"^(feat|fix)(\([^)]*\))?!?:", re.IGNORECASE)

#: Paths whose bytes a generator owns. A pull request whose only non-test work
#: lives here is a regeneration, and its tests pin generated bytes rather than
#: behaviour, so it is not a task. The list mirrors the Generated Artifacts Map
#: in CLAUDE.md.
GENERATED_PREFIXES = (
    "skills/",
    "agent-skills/",
    "examples/use-cases/",
    "site/",
    "src/plugin_bundle/omh/tools/capability_families.json",
    "docs/WORKFLOWS.md",
    "docs/ROLES.md",
    "CHANGELOG.md",
    "README.md",
)

#: Dependency, packaging, and CI surfaces. A pull request confined to these is
#: maintenance, not a coding task with a behavioural validator.
INFRASTRUCTURE_PREFIXES = (
    ".github/",
    "packaging/",
    "install.sh",
    "install.ps1",
    "pyproject.toml",
    "uv.lock",
    ".gitignore",
    ".gitattributes",
)

TEST_PREFIX = "tests/"
SOURCE_PREFIX = "src/"

#: Headings whose text describes the problem rather than the fix. The PR body
#: fallback takes the first of these that the body actually carries.
PROBLEM_HEADINGS = ("Why This Exists", "Problem", "Motivation")

#: Headings that describe the change. Everything from the first one onwards is
#: dropped from a PR-body task text, because it names the solution.
#:
#: These match by prefix, not by equality, because a heading in the wild
#: carries qualifiers. This repository's own pull request template writes
#: `### Implementation (boundary level)`, which equals no string such a list
#: would ever hold, so an equality test left the entire implementation section
#: inside the task text.
SOLUTION_HEADINGS = (
    "What Changed",
    "How It Works",
    "Files And Contracts Touched",
    "Implementation",
    "Validation",
    "Observed Evidence",
    "Proposal",
    # An issue prescribes the fix under headings of its own, and those sections
    # name the change to make just as directly as a pull request body does.
    "Suggested fix",
    "Proposed fix",
    "Root cause",
    "Verification",
    "Solution",
    "Approach",
)

MAX_CHANGED_LINES = 400
MAX_REGRESSION_MODULES = 6
MIN_TASK_TEXT_CHARS = 200
MAX_TASK_TEXT_CHARS = 8_000

#: An added source line at least this long is specific enough that finding it
#: verbatim in the task text proves the task leaks the solution.
LEAK_LINE_MIN_CHARS = 40


class CorpusError(RuntimeError):
    """The corpus could not be built or does not verify."""


def _is_generated(path: str) -> bool:
    return any(
        path == prefix or path.startswith(prefix) for prefix in GENERATED_PREFIXES
    )


def _is_infrastructure(path: str) -> bool:
    return any(
        path == prefix or path.startswith(prefix) for prefix in INFRASTRUCTURE_PREFIXES
    )


def _is_test(path: str) -> bool:
    return path.startswith(TEST_PREFIX)


def _is_test_module(path: str) -> bool:
    return _is_test(path) and Path(path).name.startswith("test_") and path.endswith(".py")


def heading_matches(title: str, heading: str) -> bool:
    """Whether a markdown heading in the wild is the section ``heading`` names.

    Prefix, not equality. A real heading carries qualifiers -- this
    repository's pull request template writes `Implementation (boundary
    level)` -- and an equality test silently keeps the section it was supposed
    to cut. The boundary after the prefix has to be a non-word character so
    `Fix` does not swallow `Fixture`, and a trailing colon is dropped because
    `Root cause:` is the same heading as `Root cause`.
    """

    normalized = " ".join(title.strip().strip("*_`#").split()).rstrip(":").casefold()
    wanted = " ".join(heading.split()).casefold()
    if normalized == wanted:
        return True
    return normalized.startswith(wanted) and not normalized[len(wanted)].isalnum()


def _section(body: str, headings: Sequence[str]) -> tuple[str, int] | None:
    """The first markdown section whose heading matches, with its offset."""

    for match in _headings_outside_code(body):
        title = match.group(1)
        for heading in headings:
            if heading_matches(title, heading):
                return heading, match.start()
    return None


def _headings_outside_code(body: str) -> list[re.Match[str]]:
    """Heading matches that are not inside a fenced code block.

    A `#` line inside a fence is a shell comment or a Python comment, not a
    section, and treating one as a section cuts the task text at a place the
    author never wrote a boundary.
    """

    fenced: list[tuple[int, int]] = []
    opened: int | None = None
    for fence in re.finditer(r"^\s*(?:```|~~~)", body, re.MULTILINE):
        if opened is None:
            opened = fence.start()
        else:
            fenced.append((opened, fence.end()))
            opened = None
    if opened is not None:
        fenced.append((opened, len(body)))
    return [
        match
        for match in re.finditer(r"^#{1,4}\s*(.+?)\s*$", body, re.MULTILINE)
        if not any(start <= match.start() < end for start, end in fenced)
    ]


#: A home directory in a public issue body, which is somebody's username.
#: The lane's artifact rule only refuses a string that *starts with* a home
#: path, so one quoted mid-sentence rode into the committed corpus: a real
#: contributor's name, from a public issue, republished in this repository as
#: benchmark data. Redacted at build time, where it is cheap; the surrounding
#: sentence still reads and the task still states the same problem.
HOME_DIRECTORY = re.compile(
    r"(?:/Users/|/home/|[A-Za-z]:\\\\?Users\\\\?)[A-Za-z0-9._-]+", re.IGNORECASE
)


def redact_home_directories(text: str) -> str:
    """Replace any home directory path with a placeholder of the same shape."""

    return HOME_DIRECTORY.sub("<home>", text)


def task_text_from_pull_request_body(body: str) -> str:
    """The problem half of a PR body, with the solution half removed."""

    found = _section(body, PROBLEM_HEADINGS)
    if found is None:
        return ""
    _heading, start = found
    body_from_problem = body[start:]
    cut = _section(body_from_problem[1:], SOLUTION_HEADINGS)
    if cut is not None:
        body_from_problem = body_from_problem[: cut[1] + 1]
    lines = body_from_problem.splitlines()
    return "\n".join(lines[1:]).strip()


def strip_solution_sections(body: str) -> str:
    """An issue body with its proposal half removed."""

    cut = _section(body, SOLUTION_HEADINGS)
    if cut is None:
        return body.strip()
    return body[: cut[1]].strip()


def _added_lines(diff: str) -> list[str]:
    return [
        line[1:].strip()
        for line in diff.splitlines()
        if line.startswith("+") and not line.startswith("+++")
    ]


def leaked_solution_lines(task_text: str, source_diff: str) -> list[str]:
    """Added non-test lines that appear verbatim in the task text."""

    normalized = " ".join(task_text.split())
    leaks = []
    for line in _added_lines(source_diff):
        if len(line) < LEAK_LINE_MIN_CHARS:
            continue
        if " ".join(line.split()) in normalized:
            leaks.append(line)
    return leaks


#: A name the pull request defines: a function, a class, or a module-level
#: constant, read off its added source lines. The indentation is already gone
#: by the time these lines are seen, so a nested definition reads as a
#: top-level one; for a leak signal that over-counts in the safe direction.
DEFINITION = re.compile(
    r"^(?:async\s+)?def\s+(?P<function>[A-Za-z_]\w{3,})"
    r"|^class\s+(?P<klass>[A-Za-z_]\w{3,})"
    r"|^(?P<constant>[A-Z][A-Z0-9_]{4,})\s*(?::[^=]+)?="
)


def defined_names(source_diff: str) -> list[str]:
    """Every function, class, or constant name the diff's added lines define."""

    names: set[str] = set()
    for line in _added_lines(source_diff):
        match = DEFINITION.match(line)
        if match is None:
            continue
        names.update(value for value in match.groupdict().values() if value)
    return sorted(names)


def introduced_names_in_task_text(
    repository: Path, base: str, task_text: str, source_diff: str
) -> list[str]:
    """Names the task text hands over that did not exist before the fix.

    The verbatim-line rule cannot catch this. A pull request body paraphrases
    rather than quotes, so it names the function to write without ever
    reproducing a line of it, and the task becomes transcription: the hidden
    validator asserts on exactly that name.

    A name counts only when the pull request defines it AND the task text uses
    it AND `git grep` finds it nowhere under `src/` at the merge base. The last
    condition is what separates handing over the answer from naming something
    the candidate could have read for itself.
    """

    words = set(re.findall(r"[A-Za-z_]\w+", task_text))
    candidates = [name for name in defined_names(source_diff) if name in words]
    if not candidates:
        return []
    return sorted(
        name
        for name in candidates
        if not repo_lib.grep_paths(repository, base, [name], SOURCE_PREFIX)
    )


def source_paths_in_task_text(task_text: str, source_paths: Sequence[str]) -> list[str]:
    """The pull request's own changed source files that the task text names.

    Weaker than a name leak and deliberately not an exclusion: pointing at the
    file that misbehaves is what an ordinary bug report does, and it hands over
    no part of the fix. It is recorded so a reader can subset the corpus.
    """

    return sorted(path for path in source_paths if path in task_text)


#: How much of the answer a task's text still carries, worst class first. A
#: task is `clean` only when none of the weaker signals fires.
#:
#: Recorded per task rather than argued about in prose, because the honest
#: reading of any published number depends on which of these classes the tasks
#: behind it belong to, and a reader holding the field can subset the corpus
#: instead of trusting a sentence about it.
LEAK_CLASSES = (
    "heading_prescriptive",
    "names_new_identifier",
    "names_changed_file",
    "clean",
)


def has_prescriptive_heading(task_text: str) -> bool:
    """Whether a solution-describing heading survived into the task text.

    The cut removes everything from the first such heading onwards, so this
    should never fire. It is checked and recorded anyway: the cut matches a
    list of headings, that list is not the set of all headings an author might
    write, and a corpus that assumes its own filter is exhaustive has no way to
    discover that it is not.
    """

    return _section(task_text, SOLUTION_HEADINGS) is not None


def leak_class(
    *,
    prescriptive_heading: bool,
    introduced_names: Sequence[str],
    named_paths: Sequence[str],
) -> str:
    """The worst leak signal a task's text still carries."""

    if prescriptive_heading:
        return "heading_prescriptive"
    if introduced_names:
        return "names_new_identifier"
    if named_paths:
        return "names_changed_file"
    return "clean"


def _touched_packages(source_paths: Iterable[str]) -> list[str]:
    packages = set()
    for path in source_paths:
        parts = Path(path).parts
        if len(parts) >= 3 and parts[0] == "src":
            packages.add(parts[1])
    return sorted(packages)


def _regression_modules(
    repository: Path,
    merge_base: str,
    packages: Sequence[str],
    touched_tests: Sequence[str],
    limit: int,
) -> list[str]:
    """Pre-existing test modules for the touched packages, smallest first.

    Smallest first is a runtime choice, not a coverage choice: these modules
    run once per arm per task, so the budget is real. The selection is
    deterministic, and the chosen list is pinned in the corpus, so a later run
    grades against exactly the same regression set.
    """

    if not packages:
        return []
    touched = set(touched_tests)
    needles = tuple(f"omh.{package}" for package in packages)
    sizes = repo_lib.blob_sizes(repository, merge_base, TEST_PREFIX)
    scored = sorted(
        (sizes.get(path, 0), path)
        for path in repo_lib.grep_paths(repository, merge_base, needles, TEST_PREFIX)
        if _is_test_module(path) and path not in touched
    )
    return sorted(path for _size, path in scored[:limit])


def verification_commands(regression_modules: Sequence[str]) -> list[str]:
    """The checks the OMH arm's verification gate is allowed to run.

    These are checks a candidate could legitimately run itself. The pull
    request's own test modules are deliberately absent: they are the hidden
    validator, and a gate that ran them would hand the candidate the answer.
    """

    commands = ["python -m compileall -q src"]
    if regression_modules:
        commands.append(
            "python -m unittest " + " ".join(regression_modules)
        )
    return commands


def _candidate(
    repository: Path,
    repository_name: str,
    pull_request: Mapping[str, Any],
    regression_limit: int,
) -> tuple[dict[str, Any] | None, str]:
    """One pull request as a task, or ``(None, reason)`` when it is excluded."""

    number = int(pull_request["number"])
    title = str(pull_request.get("title") or "")
    if not TITLE_PREFIX.match(title.strip()):
        return None, "not_feat_or_fix"
    merge_commit = pull_request.get("mergeCommit") or {}
    head = str(merge_commit.get("oid") or "")
    if not head:
        return None, "no_merge_commit"
    try:
        head = repo_lib.resolve(repository, head)
        base = repo_lib.merge_base_of(repository, head)
    except repo_lib.GitError:
        return None, "commit_not_in_local_history"

    rows = repo_lib.changed_paths(repository, base, head)
    paths = [path for _status, path in rows]
    if not paths:
        return None, "empty_diff"
    test_paths = sorted(path for path in paths if _is_test(path))
    test_modules = sorted(path for path in test_paths if _is_test_module(path))
    source_paths = sorted(
        path
        for path in paths
        if path.startswith(SOURCE_PREFIX)
        and path.endswith(".py")
        and not _is_generated(path)
    )
    if not test_modules:
        return None, "no_test_module"
    if not source_paths:
        return None, "no_source_change"
    if all(_is_infrastructure(path) or _is_test(path) for path in paths):
        return None, "infrastructure_only"
    non_test_work = [
        path for path in paths if not _is_test(path) and not _is_generated(path)
    ]
    if not non_test_work:
        return None, "generated_artifacts_only"
    # The complete non-test change, for the probe's reference solution.
    solution_paths = [path for path in paths if not _is_test(path)]

    counts = repo_lib.numstat(repository, base, head)
    # The cap bounds the work a candidate has to produce, so it counts the
    # non-test, non-generated change only. Test lines are the validator, and a
    # thorough test file does not make the task bigger; generated bytes are a
    # regeneration the candidate is never asked to reproduce by hand.
    changed_lines = sum(
        added + deleted
        for path, (added, deleted) in counts.items()
        if not _is_generated(path) and not _is_test(path)
    )
    test_lines = sum(
        added + deleted for path, (added, deleted) in counts.items() if _is_test(path)
    )
    if changed_lines > MAX_CHANGED_LINES:
        return None, "over_changed_line_cap"

    issues = pull_request.get("closingIssuesReferences") or []
    issue_number = None
    task_text = ""
    task_source = ""
    for issue in issues:
        if not isinstance(issue, Mapping):
            continue
        candidate_number = issue.get("number")
        if not isinstance(candidate_number, int):
            continue
        body = strip_solution_sections(issue_body(repository_name, candidate_number))
        if len(body) >= MIN_TASK_TEXT_CHARS:
            issue_number = candidate_number
            task_text = body
            task_source = "linked_issue"
            break
    if not task_text:
        task_text = task_text_from_pull_request_body(str(pull_request.get("body") or ""))
        task_source = "pull_request_body"
    task_text = redact_home_directories(task_text.strip())
    if len(task_text) < MIN_TASK_TEXT_CHARS:
        return None, "task_text_too_short"
    task_text = task_text[:MAX_TASK_TEXT_CHARS]

    source_diff = repo_lib.diff_text(repository, base, head, non_test_work)
    leaks = leaked_solution_lines(task_text, source_diff)
    if leaks:
        return None, "task_text_leaks_solution"
    introduced = introduced_names_in_task_text(repository, base, task_text, source_diff)
    if introduced:
        # The task text names something the fix creates and the hidden
        # validator asserts on. Both arms would be transcribing rather than
        # solving, which inflates the pass rate and compresses the delta.
        return None, "task_text_names_an_introduced_definition"
    named_source_paths = source_paths_in_task_text(task_text, source_paths)
    prescriptive_heading = has_prescriptive_heading(task_text)
    classification = leak_class(
        prescriptive_heading=prescriptive_heading,
        introduced_names=introduced,
        named_paths=named_source_paths,
    )

    packages = _touched_packages(source_paths)
    regression = _regression_modules(
        repository, base, packages, test_paths, regression_limit
    )
    test_diff = repo_lib.diff_text(repository, base, head, test_paths)
    if not test_diff.strip():
        return None, "empty_test_diff"

    task = {
        "task_id": f"PR-{number}",
        "pull_request": number,
        "title": title.strip(),
        "kind": TITLE_PREFIX.match(title.strip()).group(1).casefold(),
        "merge_commit": head,
        "merge_base": base,
        "issue": issue_number,
        "task_source": task_source,
        "task_text": task_text,
        "task_text_sha256": lane.text_digest(task_text),
        # Recorded, not excluded: naming the file that misbehaves is what an
        # ordinary bug report does. A reader who wants the stricter corpus
        # subsets on this field rather than trusting a prose claim about it.
        "task_text_names_source_paths": named_source_paths,
        "leak_class": classification,
        "changed_lines": changed_lines,
        "test_lines": test_lines,
        "touched_packages": packages,
        "source_paths": source_paths,
        "test_paths": test_paths,
        "test_modules": test_modules,
        "test_blobs": {path: repo_lib.blob_digest(repository, head, path) for path in test_paths},
        # The pull request's own non-test change: the reference solution. Only
        # the probe reads it, to prove the task is solvable at all; no arm ever
        # sees it and no run writes it into a candidate workspace.
        #
        # Every non-test path, generated artifacts included. They are left out
        # of the line cap and the leak scan for good reasons -- a regeneration
        # is not work the candidate has to produce by hand, and generated bytes
        # are not a solution to quote -- but the reference solution has to be
        # the whole change or the green direction measures the wrong thing:
        # this repository's tests assert generated bytes, so a solution missing
        # them stays red and the task is rejected as unsolvable when it is not.
        "solution_paths": sorted(solution_paths),
        "solution_blobs": {
            path: repo_lib.blob_digest(repository, head, path)
            for path in sorted(solution_paths)
        },
        "test_diff_sha256": lane.text_digest(test_diff),
        "regression_modules": regression,
        "verification_commands": verification_commands(regression),
    }
    return task, "included"


def build(
    *,
    repository: Path,
    repository_name: str,
    limit: int,
    regression_limit: int = MAX_REGRESSION_MODULES,
    maximum_tasks: int | None = None,
) -> dict[str, Any]:
    """Select tasks from merged pull requests; network reads happen here only."""

    excluded: dict[str, int] = {}
    tasks: list[dict[str, Any]] = []
    for pull_request in merged_pull_requests(repository_name, limit):
        task, reason = _candidate(
            repository, repository_name, pull_request, regression_limit
        )
        if task is None:
            excluded[reason] = excluded.get(reason, 0) + 1
            continue
        tasks.append(task)
        if maximum_tasks is not None and len(tasks) >= maximum_tasks:
            break
    tasks.sort(key=lambda item: item["pull_request"])
    return {
        "schema_version": lane.CORPUS_SCHEMA,
        "repository": repository_name,
        "selection": {
            "pull_requests_read": limit,
            "max_changed_lines": MAX_CHANGED_LINES,
            "regression_module_limit": regression_limit,
            "excluded": dict(sorted(excluded.items())),
        },
        "tasks": tasks,
        "corpus_digest": corpus_digest(tasks),
    }


#: What two probe passes have to agree on for a candidate to be a task. The
#: status alone is not enough: a validator whose verdict turns on the checkout
#: path can be red under both roots and red about different things.
PROBE_VERDICT_FIELDS = ("status", "ran", "failures", "errors")

#: The second probe pass runs under a root deliberately deeper and longer than
#: the first. A fixture that spends the checkout path inside a length-capped
#: string is only exposed when the two roots differ in length; two roots of the
#: same shape agree by construction and prove nothing.
SECOND_PASS_NESTING = ("second-workspace-root", "deliberately-one-level-deeper")


def probe_passes_agree(first: Mapping[str, Any], second: Mapping[str, Any]) -> bool:
    """Whether two runs of one validator reached the same verdict."""

    return all(first.get(field) == second.get(field) for field in PROBE_VERDICT_FIELDS)


def probe(
    *,
    repository: Path,
    payload: Mapping[str, Any],
    python_executable: str,
    workspace_root: Path,
    timeout: int,
    maximum_tasks: int | None = None,
) -> dict[str, Any]:
    """Prove every task is a task, offline, before any arm is ever run.

    A task is only a task if it is red before the fix and green after it. Both
    directions are checked, because either one alone lets a bad task through:

    * at the merge base the pull request's own tests must be RED and its
      regression modules GREEN. A validator that is already green needs
      nothing built, and a regression set that is already red fails every arm
      for a reason no arm caused;
    * with the pull request's own non-test change applied, the same validator
      and the same regression modules must both be GREEN. Without this an
      unsolvable task enters silently, costs a call on every arm, and deflates
      the published pass rate.

    The validator runs twice, under two workspace roots that differ in depth
    and in length, and both runs have to report the same verdict: the same
    status *and* the same counts, not merely the same colour. A task that
    disagrees with itself between two checkout paths would credit or fault an
    arm for the directory the harness happened to pick, so it is rejected
    rather than averaged over.

    The counts are the part that bites, and a real candidate is why. PR-1502
    fixes a fixture that built a verification command out of the checkout path
    and compared it against a 240-character cap, so at its own merge base the
    fixture's verdict turned on how long the workspace path happened to be;
    that pull request's own body reports it passing from one worktree and
    erroring from another on the same commit. Both of this probe's roots are
    long enough to trip that cap, so a status-only comparison saw red twice and
    kept the task. What the two passes disagreed on was which assertions broke,
    and that disagreement is the path dependence itself.
    """

    import grading  # noqa: PLC0415

    kept: list[dict[str, Any]] = []
    rejected: dict[str, int] = {}
    probed = 0
    # Issue-sourced candidates first, then newest first within each group,
    # stopping as soon as the corpus is full.
    #
    # The ordering is the headline's. A task whose text came from the pull
    # request body was written after the fix by its author, so only the
    # issue-sourced tasks can carry a sentence about solving this repository's
    # own issues. The probe rejects some of every group, so taking them in
    # merge order would let pull-request-body tasks consume slots the headline
    # subset needs, and the headline's `n` is the number under the most
    # pressure.
    #
    # Newest first inside each group because the probe runs each candidate's
    # validator twice and its regression set once, which costs minutes on this
    # repository's larger modules, and sweeping candidates past a full corpus
    # buys nothing.
    candidates = sorted(
        payload["tasks"],
        key=lambda item: (
            str(item.get("task_source")) != "linked_issue",
            -int(item["pull_request"]),
        ),
    )
    def one_pass(
        task: Mapping[str, Any],
        root: Path,
        name: str,
        *,
        with_regression: bool,
        with_solution: bool = False,
    ) -> tuple[dict, dict]:
        task_id = str(task["task_id"])
        with repo_lib.candidate_workspace(
            repository, str(task["merge_base"]), root, name
        ) as workspace:
            scratch = root / f"scratch-{task_id}"
            scratch.mkdir(parents=True, exist_ok=True)
            try:
                if with_solution:
                    grading.materialize_solution(repository, task, workspace)
                grading.materialize_validator(repository, task, workspace)
                grading.restore_regression_modules(repository, task, workspace)
                target = grading.run_modules(
                    python_executable=python_executable,
                    workspace=workspace,
                    scratch=scratch,
                    modules=list(task["test_modules"]),
                    timeout=timeout,
                )
                regression = (
                    grading.run_modules(
                        python_executable=python_executable,
                        workspace=workspace,
                        scratch=scratch,
                        modules=list(task["regression_modules"]),
                        timeout=timeout,
                    )
                    if with_regression
                    else {"status": "green"}
                )
            finally:
                shutil.rmtree(scratch, ignore_errors=True)
        return target, regression

    for task in candidates:
        if maximum_tasks is not None and len(kept) >= maximum_tasks:
            break
        probed += 1
        task_id = str(task["task_id"])
        target, regression = one_pass(
            task, workspace_root, f"probe-{task_id}", with_regression=True
        )
        verdict = "included"
        if target["status"] == "green":
            verdict = "validator_already_green_at_merge_base"
        elif target["status"] == "error":
            verdict = "validator_did_not_reach_a_verdict"
        elif regression["status"] != "green":
            verdict = "regression_set_not_green_at_merge_base"
        second: dict[str, Any] = {}
        if verdict == "included":
            # A different ROOT, not just a different leaf name, and a root that
            # differs in length as well as in spelling. Both halves matter: a
            # second pass that renamed the leaf agreed with the first every
            # time, and the dependence this check exists for turns on how many
            # characters the path spends.
            with TemporaryDirectory(prefix="omh-product-ab-second-") as other_root:
                deeper = Path(other_root).joinpath(*SECOND_PASS_NESTING)
                deeper.mkdir(parents=True, exist_ok=True)
                second, _ = one_pass(
                    task, deeper, f"{task_id}-hermes", with_regression=False
                )
            if not probe_passes_agree(target, second):
                verdict = "verdict_depends_on_workspace_path"
        solved: dict[str, Any] = {}
        solved_regression: dict[str, Any] = {}
        if verdict == "included":
            # The other direction. Red at the merge base proves nothing has to
            # be built; it does not prove anything CAN be. A task whose
            # validator stays red even with the change that actually shipped is
            # unsolvable here -- it depends on something outside the
            # candidate's reach -- and it would burn budget on every arm and
            # pull the published pass rate down for a reason no arm caused.
            with TemporaryDirectory(prefix="omh-product-ab-solution-") as solution_root:
                solved, solved_regression = one_pass(
                    task,
                    Path(solution_root),
                    f"{task_id}-solved",
                    with_regression=True,
                    with_solution=True,
                )
            if solved["status"] != "green" or solved_regression["status"] != "green":
                verdict = "validator_not_green_with_the_reference_fix"
        if verdict != "included":
            rejected[verdict] = rejected.get(verdict, 0) + 1
            continue
        annotated = dict(task)
        annotated["baseline_probe"] = {
            "with_reference_fix": {
                key: solved[key] for key in ("status", "ran", "failures", "errors")
            },
            "with_reference_fix_regression": {
                key: solved_regression[key]
                for key in ("status", "ran", "failures", "errors")
            },
            "target": {key: target[key] for key in ("status", "ran", "failures", "errors")},
            "target_second_path": {
                key: second[key] for key in ("status", "ran", "failures", "errors")
            },
            "regression": {key: regression[key] for key in ("status", "ran", "failures", "errors")},
        }
        kept.append(annotated)
    kept.sort(key=lambda item: int(item["pull_request"]))
    result = dict(payload)
    result["tasks"] = kept
    selection = dict(result.get("selection") or {})
    selection["probe_rejected"] = dict(sorted(rejected.items()))
    selection["probed"] = probed
    selection["max_tasks"] = maximum_tasks
    # The headline subset's size, recorded rather than left to be counted.
    # Only issue-sourced tasks can carry a sentence about solving this
    # repository's own issues, so that `n` is the one a reader needs beside
    # any such number.
    selection["task_source"] = _counts(str(task.get("task_source")) for task in kept)
    selection["leak_class"] = _counts(str(task.get("leak_class")) for task in kept)
    selection["leak_class_issue_sourced"] = _counts(
        str(task.get("leak_class"))
        for task in kept
        if str(task.get("task_source")) == "linked_issue"
    )
    result["selection"] = selection
    result["corpus_digest"] = corpus_digest(kept)
    return result


def _counts(values: Iterable[str]) -> dict[str, int]:
    counts: dict[str, int] = {}
    for value in values:
        counts[value] = counts.get(value, 0) + 1
    return dict(sorted(counts.items()))


def corpus_digest(tasks: Sequence[Mapping[str, Any]]) -> str:
    """One digest over everything a run depends on."""

    return lane.digest(
        [
            [
                task["task_id"],
                task["merge_base"],
                task["merge_commit"],
                task["task_text_sha256"],
                task["test_diff_sha256"],
                sorted(task["test_modules"]),
                sorted(task["regression_modules"]),
                list(task["verification_commands"]),
                # The reference solution the probe proves the task against. No
                # arm reads it, but a run's meaning depends on the task having
                # been proven solvable, so it belongs under the digest.
                sorted((task.get("solution_blobs") or {}).items()),
            ]
            for task in sorted(tasks, key=lambda item: str(item["task_id"]))
        ]
    )


def load(path: Path) -> dict[str, Any]:
    payload = lane.load_object(path)
    if payload.get("schema_version") != lane.CORPUS_SCHEMA:
        raise CorpusError(f"{path} is not {lane.CORPUS_SCHEMA}")
    tasks = payload.get("tasks")
    if not isinstance(tasks, list) or not tasks:
        raise CorpusError("corpus carries no task")
    return payload


def verify(repository: Path, payload: Mapping[str, Any]) -> list[str]:
    """Re-derive every pinned digest from the local object store."""

    errors: list[str] = []
    tasks = list(payload["tasks"])
    if corpus_digest(tasks) != payload.get("corpus_digest"):
        errors.append("corpus_digest does not match the task list")
    for task in tasks:
        task_id = str(task["task_id"])
        if lane.text_digest(str(task["task_text"])) != task["task_text_sha256"]:
            errors.append(f"{task_id}: task text digest drifted")
        try:
            base = repo_lib.resolve(repository, str(task["merge_base"]))
            head = repo_lib.resolve(repository, str(task["merge_commit"]))
        except repo_lib.GitError:
            errors.append(f"{task_id}: merge base or merge commit is not in this checkout")
            continue
        if base != task["merge_base"] or head != task["merge_commit"]:
            errors.append(f"{task_id}: pinned commits did not resolve to themselves")
        diff = repo_lib.diff_text(repository, base, head, list(task["test_paths"]))
        if lane.text_digest(diff) != task["test_diff_sha256"]:
            errors.append(f"{task_id}: test diff digest drifted")
        for path, expected in dict(task["test_blobs"]).items():
            if repo_lib.blob_digest(repository, head, str(path)) != expected:
                errors.append(f"{task_id}: test file digest drifted for {path}")
        # The reference solution is under the corpus digest, so it has to
        # re-derive too: a task is only as proven-solvable as the change the
        # probe actually applied.
        for path, expected in dict(task.get("solution_blobs") or {}).items():
            if repo_lib.blob_digest(repository, head, str(path)) != expected:
                errors.append(f"{task_id}: solution file digest drifted for {path}")
        leaked = [
            path
            for path in task["test_paths"]
            if repo_lib.blob_digest(repository, base, str(path)) == task["test_blobs"][path]
        ]
        if leaked:
            errors.append(
                f"{task_id}: the validator is already present at the merge base: {sorted(leaked)}"
            )
    return errors
